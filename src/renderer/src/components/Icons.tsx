// Returns the correct React element icon for a given filename, VSCode-style
export function getFileIcon(fileName: string, size = 14, selected = false): React.ReactElement {
  const lower = fileName.toLowerCase()
  if (lower.endsWith('.pdf')) {
    return <PdfIcon size={size} />
  }
  if (lower.endsWith('.html') || lower.endsWith('.htm')) {
    return <HtmlIcon size={size} />
  }
  if (lower.endsWith('.md') || lower.endsWith('.markdown')) {
    return <MarkdownIcon size={size} />
  }
  if (lower.endsWith('.css')) {
    return <CssIcon size={size} />
  }
  if (lower.endsWith('.js') || lower.endsWith('.jsx')) {
    return <JsIcon size={size} />
  }
  if (lower.endsWith('.json')) {
    return <JsonIcon size={size} />
  }
// Default generic file
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke={selected ? '#ffffff' : '#9ca3af'} strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round">
      <path d="M14 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V8z" />
      <polyline points="14 2 14 8 20 8" />
    </svg>
  )
}

